#!/usr/bin/env node
/**
 * Vendor Three.js out of node_modules into public/vendor/.
 *
 * There is no bundler, so the browser can't resolve the bare `three`
 * specifier. Instead the exact files the game imports are copied next to the
 * source, and the one bare import inside the addon is pointed at the copy.
 * The version comes from package.json / package-lock.json: bump `three`
 * there, `npm install`, and this script (run as `postinstall`) refreshes the
 * copies. public/vendor/ is generated and gitignored. Never edit it by hand.
 *
 * Each copy gets a one-line `.d.ts` beside it that re-exports the types from
 * `@types/three`, which is how `tsc --checkJs` sees through the relative
 * import.
 *
 *   node scripts/vendor.js           write public/vendor/
 *   node scripts/vendor.js --check   exit 1 if public/vendor/ is missing or stale
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKG = join(ROOT, 'node_modules', 'three');
const OUT = join(ROOT, 'public', 'vendor');

/**
 * What to copy. `rewrite` maps a bare specifier inside the file to a relative
 * one; `types` is the module the generated `.d.ts` re-exports.
 *
 * @type {{ from: string, to: string, types?: string, rewrite?: Record<string, string> }[]}
 */
const FILES = [
	{ from: 'build/three.module.js', to: 'three.module.js', types: 'three' },
	// three.module.js imports its other half by this exact relative name.
	{ from: 'build/three.core.js', to: 'three.core.js' },
	{
		from: 'examples/jsm/utils/BufferGeometryUtils.js',
		to: 'addons/utils/BufferGeometryUtils.js',
		types: 'three/addons/utils/BufferGeometryUtils.js',
		rewrite: { three: '../../three.module.js' },
	},
	{ from: 'LICENSE', to: 'LICENSE' },
];

/** @returns {Map<string, string>} path relative to public/vendor → contents */
function plan() {
	if (!existsSync(PKG)) {
		throw new Error('node_modules/three is missing. Run `npm install` first.');
	}
	const { version } = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8'));
	/** @type {Map<string, string>} */
	const out = new Map();
	for (const f of FILES) {
		let text = readFileSync(join(PKG, f.from), 'utf8');
		for (const [bare, rel] of Object.entries(f.rewrite ?? {})) {
			const before = text;
			text = text.replace(
				new RegExp(`(from\\s*)(['"])${bare}\\2`, 'g'),
				(_m, kw, q) => `${kw}${q}${rel}${q}`,
			);
			if (text === before) throw new Error(`${f.from}: no import of '${bare}' to rewrite`);
		}
		const bareLeft = /^\s*(?:import|export)\b[^'"]*from\s*['"]([^./'"][^'"]*)['"]/m.exec(text);
		if (bareLeft) {
			throw new Error(`${f.from}: bare import '${bareLeft[1]}' the browser can't resolve`);
		}
		out.set(f.to, text);
		if (f.types) {
			out.set(
				f.to.replace(/\.js$/, '.d.ts'),
				`// Generated by scripts/vendor.js. Types come from @types/three.\nexport * from '${f.types}';\n`,
			);
		}
	}
	out.set('VERSION', `three@${version}\n`);
	return out;
}

const files = plan();
if (process.argv.includes('--check')) {
	const stale = [...files].filter(([rel, text]) => {
		const p = join(OUT, rel);
		return !existsSync(p) || readFileSync(p, 'utf8') !== text;
	});
	if (stale.length) {
		console.error(
			`vendor: public/vendor/ is out of date (${stale.map(([rel]) => rel).join(', ')}). Run \`npm run vendor\`.`,
		);
		process.exit(1);
	}
	console.log(`vendor: public/vendor/ matches ${files.get('VERSION')?.trim()}`);
} else {
	rmSync(OUT, { recursive: true, force: true });
	for (const [rel, text] of files) {
		const p = join(OUT, rel);
		mkdirSync(dirname(p), { recursive: true });
		writeFileSync(p, text);
	}
	console.log(`vendor: ${files.get('VERSION')?.trim()} → public/vendor/ (${files.size} files)`);
}
